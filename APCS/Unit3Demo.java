package APCS;

public class Unit3Demo {
    public static void main(String[] args) {
        int x = 4;
        int y = 2;

        System.out.println(x + " == " + y + " is " + (x==y)); // false
        System.out.println(x + " > " + y + " is " + (x>y)); // true
        System.out.println(x + " < " + y + " is " + (x<y)); // false
        System.out.println(x + " <= " + y + " is " + (x<=y)); // false
        System.out.println(x + " >= " + y + " is " + (x>=y)); // true
        System.out.println(x + " != " + y + " is " + (x!=y)); // true
    }
}
